"""
Static dashboard generator.
Creates HTML/JS dashboard deployed to GitHub Pages.
"""
import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, List

from .config import config
from .storage import storage


class DashboardGenerator:
    """Generates static dashboard files."""

    def __init__(self):
        self.dashboard_dir = Path(config.BASE_DIR) / "dashboard"
        self.data_dir = self.dashboard_dir / "data"

    def generate(self, briefing: Dict[str, Any]) -> None:
        """Generate all dashboard files."""
        self.data_dir.mkdir(parents=True, exist_ok=True)

        # Save latest briefing data
        self._save_latest_data(briefing)

        # Generate index.html if not exists
        self._ensure_index_html()

        # Generate app.js if not exists
        self._ensure_app_js()

        # Generate style.css if not exists
        self._ensure_style_css()

    def _save_latest_data(self, briefing: Dict[str, Any]) -> None:
        """Save briefing data for dashboard consumption."""
        # Add computed fields for charts
        label_dist = briefing["summary"]["label_distribution"]
        chart_data = {
            "labels": list(label_dist.keys()),
            "values": list(label_dist.values()),
        }

        # Prepare email lists for each section
        sections_data = {}
        for key, section in briefing["sections"].items():
            sections_data[key] = {
                "title": section["title"],
                "count": section["count"],
                "emails": section["emails"],
            }

        dashboard_data = {
            "briefing": briefing,
            "chart_data": chart_data,
            "sections": sections_data,
            "last_updated": datetime.utcnow().isoformat() + "Z",
        }

        with open(config.LATEST_BRIEFING_FILE, "w", encoding="utf-8") as f:
            json.dump(dashboard_data, f, indent=2, ensure_ascii=False)

